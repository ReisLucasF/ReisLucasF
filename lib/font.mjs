// diacríticos: 2 linhas acima da letra (−2, −1) e 2 abaixo (7, 8) para a cedilha
const MARK = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circ: ['..#..', '.#.#.'],
  tilde: ['.##.#', '#.##.'],
  uml: ['.#.#.', '.....'],
};
const ACC = {
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'tilde'], Ä: ['A', 'uml'],
  É: ['E', 'acute'], Ê: ['E', 'circ'], È: ['E', 'grave'],
  Í: ['I', 'acute'], Ì: ['I', 'grave'],
  Ó: ['O', 'acute'], Ô: ['O', 'circ'], Õ: ['O', 'tilde'], Ö: ['O', 'uml'],
  Ú: ['U', 'acute'], Ü: ['U', 'uml'],
  Ñ: ['N', 'tilde'],
};

/** Pixels (col, row) of one character; rows can be −2..8. */
function glyph(ch) {
  if (G[ch]) return pixelsOf(G[ch], 0);
  if (ACC[ch]) {
    const [base, mark] = ACC[ch];
    return [...pixelsOf(MARK[mark], -2), ...pixelsOf(G[base], 0)];
  }
  if (ch === 'Ç') return [...pixelsOf(G.C, 0), [2, 7], [1, 8], [2, 8]];
  return pixelsOf(G['?'], 0);
}
function pixelsOf(rows, r0) {
  const out = [];
  rows.forEach((row, r) => [...row].forEach((c, col) => { if (c === '#') out.push([col, r + r0]); }));
  return out;
}

export const CELL = 6; // 5 colunas + 1 de espaço

/** Width in px of `text` at pixel size `s`. */
export const textWidth = (text, s = 2, gap = 1) => Math.max(0, [...String(text)].length * (5 + gap) - gap) * s;

/**
 * Path data for `text`, top-left of the cap height at (x, y), each font pixel `s` px.
 * Pixels of a row are merged into runs to keep the SVG small.
 */
export function textPath(text, x, y, s = 2, gap = 1) {
  const rows = new Map();
  [...String(text).toUpperCase()].forEach((ch, i) => {
    for (const [c, r] of glyph(ch)) {
      const key = r;
      if (!rows.has(key)) rows.set(key, new Set());
      rows.get(key).add(i * (5 + gap) + c);
    }
  });
  let d = '';
  for (const [r, set] of rows) {
    const cols = [...set].sort((a, b) => a - b);
    for (let k = 0; k < cols.length; ) {
      let e = k;
      while (e + 1 < cols.length && cols[e + 1] === cols[e] + 1) e++;
      const px = +(x + cols[k] * s).toFixed(2), py = +(y + r * s).toFixed(2), w = (e - k + 1) * s;
      d += `M${px} ${py}h${w}v${s}h${-w}z`;
      k = e + 1;
    }
  }
  return d;
}

/** <path> element for pixel text. align: 'start' | 'middle' | 'end'. */
export function pix(text, x, y, { s = 2, fill = '#ededee', align = 'start', gap = 1, cls = '', style = '', attrs = '' } = {}) {
  const w = textWidth(text, s, gap);
  const x0 = align === 'middle' ? x - w / 2 : align === 'end' ? x - w : x;
  return `<path${cls ? ` class="${cls}"` : ''}${style ? ` style="${style}"` : ''} fill="${fill}" d="${textPath(text, x0, y, s, gap)}"${attrs}/>`;
}
